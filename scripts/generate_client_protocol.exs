defmodule Exiron.GenerateClientProtocol do
  @root Path.expand("..", __DIR__)
  @manifest_path Path.join(@root, "clients/contract/manifest.json")

  def run(args) do
    manifest = @manifest_path |> File.read!() |> Jason.decode!()

    outputs = %{
      Path.join(@root, "clients/elixir/lib/exiron_client/protocol_generated.ex") =>
        render_elixir(manifest),
      Path.join(@root, "clients/go/protocol_generated.go") => render_go(manifest)
    }

    if "--check" in args do
      stale = Enum.reject(outputs, fn {path, content} -> File.read(path) == {:ok, content} end)

      if stale != [] do
        files =
          stale
          |> Enum.map(fn {path, _content} -> Path.relative_to(path, @root) end)
          |> Enum.join(", ")

        raise "generated protocol files are stale: #{files}; run mix run scripts/generate_client_protocol.exs"
      end
    else
      Enum.each(outputs, fn {path, content} -> File.write!(path, content) end)
    end
  end

  defp render_elixir(manifest) do
    capabilities = Enum.map_join(manifest["capabilities"], ",\n", &"    #{inspect(&1)}")
    datatypes = Enum.map_join(manifest["datatypes"], ",\n", &"    #{inspect(&1)}")

    server_frame_types =
      Enum.map_join(manifest["websocket"]["server_frame_types"], ",\n", &"    #{inspect(&1)}")

    client_frame_types =
      Enum.map_join(manifest["websocket"]["client_frame_types"], ",\n", &"    #{inspect(&1)}")

    reasons =
      manifest["errors"]
      |> Map.keys()
      |> Enum.sort()
      |> Enum.map_join(",\n", fn code -> "    #{inspect(code)} => :#{code}" end)

    """
    # Generated by scripts/generate_client_protocol.exs. Do not edit by hand.
    defmodule ExironClient.Protocol.Generated do
      @moduledoc false

      @version #{inspect(manifest["protocol_version"])}
      @capabilities [
    #{capabilities}
      ]
      @datatypes [
    #{datatypes}
      ]
      @server_frame_types [
    #{server_frame_types}
      ]
      @client_frame_types [
    #{client_frame_types}
      ]
      @error_reasons %{
    #{reasons}
      }

      def version, do: @version
      def capabilities, do: @capabilities
      def datatypes, do: @datatypes
      def server_frame_types, do: @server_frame_types
      def client_frame_types, do: @client_frame_types

      def server_frame_type(type) when is_atom(type), do: server_frame_type(Atom.to_string(type))
      def server_frame_type(type) when type in @server_frame_types, do: type

      def client_frame_type(type) when is_atom(type), do: client_frame_type(Atom.to_string(type))
      def client_frame_type(type) when type in @client_frame_types, do: type

      def error_reason(code) when is_map_key(@error_reasons, code),
        do: {:ok, Map.fetch!(@error_reasons, code)}

      def error_reason(_code), do: :error
      def known_error_code?(code), do: is_map_key(@error_reasons, code)
    end
    """
  end

  defp render_go(manifest) do
    datatype_names = Enum.map(manifest["datatypes"], &"Datatype#{Macro.camelize(&1)}")
    datatype_width = datatype_names |> Enum.map(&String.length/1) |> Enum.max()

    datatype_constants =
      manifest["datatypes"]
      |> Enum.zip(datatype_names)
      |> Enum.map_join("\n", fn {datatype, name} ->
        "\t#{String.pad_trailing(name, datatype_width)} Datatype = #{inspect(datatype)}"
      end)

    capabilities = Enum.map_join(manifest["capabilities"], ",\n", &"\t#{inspect(&1)}")
    datatypes = Enum.map_join(manifest["datatypes"], ",\n", &"\tDatatype#{Macro.camelize(&1)}")

    error_codes = manifest["errors"] |> Map.keys() |> Enum.sort()
    error_width = error_codes |> Enum.map(&(inspect(&1) |> String.length())) |> Enum.max()

    errors =
      Enum.map_join(error_codes, ",\n", fn code ->
        quoted = inspect(code)
        "\t#{quoted}:#{String.duplicate(" ", error_width - String.length(quoted) + 1)}{}"
      end)

    frame_types =
      (manifest["websocket"]["server_frame_types"] ++
         manifest["websocket"]["client_frame_types"])
      |> Enum.uniq()

    frame_names = Enum.map(frame_types, &"socketFrameType#{Macro.camelize(&1)}")
    frame_width = frame_names |> Enum.map(&String.length/1) |> Enum.max()

    frame_constants =
      frame_types
      |> Enum.zip(frame_names)
      |> Enum.map_join("\n", fn frame_type ->
        {frame_type, name} = frame_type
        "\t#{String.pad_trailing(name, frame_width)} = #{inspect(frame_type)}"
      end)

    """
    // Code generated by scripts/generate_client_protocol.exs. DO NOT EDIT.

    package exiron

    // ProtocolVersion is the client contract version.
    const ProtocolVersion = #{inspect(manifest["protocol_version"])}

    const (
    #{frame_constants}
    )

    // Datatype is an Exiron payload datatype.
    type Datatype string

    const (
    #{datatype_constants}
    )

    var protocolCapabilities = [...]string{
    #{capabilities},
    }

    var protocolDatatypes = [...]Datatype{
    #{datatypes},
    }

    var protocolErrorCodes = map[string]struct{}{
    #{errors},
    }

    // SupportedCapabilities returns the capabilities defined by this client contract.
    func SupportedCapabilities() []string {
    	result := make([]string, len(protocolCapabilities))
    	copy(result, protocolCapabilities[:])
    	return result
    }

    // SupportedDatatypes returns the datatypes defined by this client contract.
    func SupportedDatatypes() []Datatype {
    	result := make([]Datatype, len(protocolDatatypes))
    	copy(result, protocolDatatypes[:])
    	return result
    }
    """
  end
end

Exiron.GenerateClientProtocol.run(System.argv())
